import pandas as pd
import matplotlib.pyplot as plt

# بيانات مبيعات تجريبية - مشروع عرفة
data = {
    'الشهر': ['يناير','فبراير','مارس','ابريل','مايو','يونيو'],
    'المبيعات': [15000, 18000, 12000, 22000, 25000, 30000]
}
df = pd.DataFrame(data)

print("📊 تحليل مبيعات - Arafa Said")
print(df)
print(f"\n✅ إجمالي المبيعات: {df['المبيعات'].sum()} جنيه")
print(f"📈 متوسط المبيعات: {df['المبيعات'].mean()} جنيه")
print(f"🚀 توقع الشهر القادم: {int(df['المبيعات'].mean() * 1.2)} جنيه (بزيادة 20% بالذكاء الاصطناعي)")

# رسم بياني
plt.plot(df['الشهر'], df['المبيعات'])
plt.title('مبيعات 6 شهور')
plt.savefig('sales.png')